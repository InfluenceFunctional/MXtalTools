"""Orthorhombic axis order: the cell step of ``canon.canonicalize`` for space groups 16-74.

Above the monoclinic groups the only setting changes that keep ``SYM_OPS[sg]`` and are not isometries of the group's
generic metric (so that ``domains.fold`` cannot absorb them) are the orthorhombic axis permutations (survey and
adversarial check of 2026-10-21, four independent enumerations). In every group 75-230 the metric-preserving setting
changes are exactly the linear parts of Gamma, which the fold absorbs, so there the standard cell is canonical once
snapped to the group's exact metric (``canon``).

Derivation (``axis_orders``; at first use, for all 59 groups at once, cached). Every det +1 signed axis permutation N
(columns: the new basis vectors in old fractional coordinates; new axis i = sign_i * old axis ``perm[i]``) is tried
with ``standardize.setting_shift`` (the origin shift on the quarter-cell grid with which N maps ``SYM_OPS[sg]`` onto
itself, the shift ``ops.change_basis`` takes by default), and each admitted (N, s) is checked exactly with
``settings.setting_matches``. Of each admitted permutation the first sign choice in ``itertools.product((1, -1))``
order is kept: the other sign choices differ from it by a diagonal 2-fold, a metric-preserving setting change, hence
an element of Gamma+ that the fold absorbs (every admitted permutation admits all four, checked at derivation). The
identity comes first. The classes found must be the survey's, otherwise ``RuntimeError`` (the tables changed): 21
groups allow one order, 26 allow a <-> b with c fixed, Pbca (61) the three cyclic orders, 11 all six.

The canonical order (``choose``): among the group's allowed orders, the lexicographically smallest
(log a, log b, log c), each component compared within ``tol`` (a relative length; ``ops._lex_select``). With k the
number of allowed orders: k = 6 gives a <= b <= c; k = 2, a <= b; Pbca the shortest axis first and, when the two
shortest are equal within ``tol``, the cyclic order with b <= c; k = 1 leaves the cell as given.

The chart of these cells (``OrthoCellChart``; the units of ``canon``'s ``near_face`` and ``nudge`` for these groups)
is y = (log a, log b, log c), and the canonical domain is {y : A y >= 0} with the face rows A (``AxisOrders.faces``):
k = 6: log b - log a and log c - log b; k = 2: log b - log a; Pbca: log b - log a and log c - log a; k = 1: none. A
face value is a difference of log lengths (a relative length difference), as the FREE monoclinic face log c - log a
of ``charts.CellChart`` is. The faces of the k = 6 and k = 2 classes are mirrors (an allowed transposition fixes the
face pointwise: a cell on one has two equally good orders, a special metric, ``n_auto`` 2). Pbca's two faces are
seams glued by the 3-cycle: a cell on one has one canonical order, chosen by the tie-break, and only the cone point
a = b = c is a special metric (``n_auto`` 3).

``n_auto`` is the order of the subgroup generated by the allowed orders that give the chosen cell within ``face_tol``
(each compared on its own, max over the three log lengths), so it is always 1, 2, 3 or 6. Comparing within a
tolerance is not transitive: in the six-order class a chain of near-ties (b - a and c - b within ``face_tol``, c - a
not) has the two transpositions within ``face_tol`` and not the 3-cycles; they generate all six orders, as a
single-linkage merge of the log lengths within ``face_tol`` would. In the two-order class and Pbca the orders within
``face_tol`` already form a subgroup (a 3-cycle within it brings its inverse), so a Pbca chain off the cone stays
``n_auto`` 1.
"""
import itertools
from dataclasses import dataclass
from typing import Dict, Tuple

import numpy as np
import torch

F64 = torch.float64

#: the orthorhombic space groups
ORTHORHOMBIC = tuple(range(16, 75))

#: number of allowed orders -> class name
KINDS = {1: 'one', 2: 'swap_ab', 3: 'cyclic', 6: 'all'}

#: the survey of 2026-10-21: number of groups per number of allowed orders, and the only cyclic group
SURVEY_COUNTS = {1: 21, 2: 26, 3: 1, 6: 11}
SURVEY_CYCLIC = (61,)

_IDENTITY = (0, 1, 2)
_SWAP_AB = (1, 0, 2)
_CYCLES = ((1, 2, 0), (2, 0, 1))

_ORDERS: Dict[int, 'AxisOrders'] = {}
_CHARTS: Dict[int, 'OrthoCellChart'] = {}


@dataclass(frozen=True, eq=False)
class AxisOrders:
    """The axis orders one orthorhombic space group allows, in the setting of ``SYM_OPS[sg]``.

    Attributes
    ----------
    sg : int
    kind : str
        ``'one'``, ``'swap_ab'`` (a <-> b, c fixed), ``'cyclic'`` (Pbca) or ``'all'`` (``KINDS``).
    perm : torch.Tensor
        [k, 3] long: order j puts old axis ``perm[j, i]`` at new axis i (new lengths ``L[perm[j]]``); row 0 is the
        identity.
    N : torch.Tensor
        [k, 3, 3] long, det +1: the basis change of each order, ``x_old = N x_new + s`` (``ops.change_basis``).
    s : torch.Tensor
        [k, 3] float64: its origin shift (quarter-cell grid, ``standardize.setting_shift``).
    faces : torch.Tensor
        [m, 3] float64 rows A of the canonical domain {A y >= 0} in y = (log a, log b, log c); m = 0 for k = 1.
    mirror : bool
        The faces are mirrors (k = 6, 2); False for the seams of Pbca and for k = 1.
    comp : torch.Tensor
        [k, k] long: ``comp[i, j]`` is the index of the order ``perm[i][perm[j]]`` (order j applied to the cell order
        i gives); the allowed orders are a group under it (checked at derivation).
    """
    sg: int
    kind: str
    perm: torch.Tensor
    N: torch.Tensor
    s: torch.Tensor
    faces: torch.Tensor
    mirror: bool
    comp: torch.Tensor

    @property
    def k(self) -> int:
        return int(self.perm.shape[0])


def _signed_permutations():
    """[(perm, signs, N int64 [3, 3])] every det +1 signed axis permutation, permutations in itertools order (identity
    first), sign choices in ``product((1, -1))`` order."""
    out = []
    for perm in itertools.permutations(range(3)):
        for signs in itertools.product((1, -1), repeat=3):
            N = np.zeros((3, 3), dtype=np.int64)
            for i, j in enumerate(perm):
                N[j, i] = signs[i]
            if round(float(np.linalg.det(N))) == 1:
                out.append((perm, signs, N))
    return out


def _faces(kind: str) -> Tuple[torch.Tensor, bool]:
    rows = {'one': [], 'swap_ab': [[-1., 1., 0.]], 'cyclic': [[-1., 1., 0.], [-1., 0., 1.]],
            'all': [[-1., 1., 0.], [0., -1., 1.]]}[kind]
    return torch.tensor(rows, dtype=F64).reshape(-1, 3), kind in ('swap_ab', 'all')


def _composition(sg: int, perms: Tuple[Tuple[int, ...], ...]) -> torch.Tensor:
    """[k, k] long ``comp[i, j]`` = index of ``perms[i][perms[j]]``; RuntimeError if the orders are not closed."""
    index = {p: j for j, p in enumerate(perms)}
    comp = []
    for p in perms:
        row = []
        for r in perms:
            q = tuple(p[x] for x in r)
            if q not in index:
                raise RuntimeError(f'sg {sg}: allowed axis orders {perms} are not closed under composition')
            row.append(index[q])
        comp.append(row)
    return torch.tensor(comp, dtype=torch.long).reshape(len(perms), len(perms))


def _derive_all() -> Dict[int, AxisOrders]:
    """``AxisOrders`` of every orthorhombic group from ``standardize.setting_shift`` and ``settings.setting_matches``;
    RuntimeError if the classes are not the survey's."""
    from mxtaltools.crystal_fd.settings import setting_matches, std_ops
    from mxtaltools.crystal_search.standardize import setting_shift
    cand = _signed_permutations()
    out = {}
    for sg in ORTHORHOMBIC:
        kept, n_signs = {}, {}
        for perm, _, N in cand:
            o = setting_shift(N.astype(np.float64), sg)
            if o is None:
                continue
            if not setting_matches(std_ops(sg), sg, N.astype(np.float64), o):
                raise RuntimeError(f'sg {sg}: setting_shift admits {N.tolist()} with shift {o.tolist()}, which '
                                   'settings.setting_matches refuses')
            n_signs[perm] = n_signs.get(perm, 0) + 1
            kept.setdefault(perm, (N, o))
        perms = tuple(kept)
        if any(v != 4 for v in n_signs.values()):
            raise RuntimeError(f'sg {sg}: an admitted axis permutation does not admit all four sign choices '
                               f'({n_signs}): the sign choice would not be absorbed by Gamma+')
        if perms == (_IDENTITY,):
            kind = 'one'
        elif perms == (_IDENTITY, _SWAP_AB):
            kind = 'swap_ab'
        elif set(perms) == {_IDENTITY, *_CYCLES} and perms[0] == _IDENTITY:
            kind = 'cyclic'
        elif len(perms) == 6:
            kind = 'all'
        else:
            raise RuntimeError(f'sg {sg}: allowed axis orders {perms} are none of the classes of the survey')
        faces, mirror = _faces(kind)
        out[sg] = AxisOrders(sg=sg, kind=kind, perm=torch.tensor(perms, dtype=torch.long),
                             N=torch.as_tensor(np.stack([kept[p][0] for p in perms])),
                             s=torch.as_tensor(np.stack([kept[p][1] for p in perms]), dtype=F64),
                             faces=faces, mirror=mirror, comp=_composition(sg, perms))
    counts = {k: sum(1 for v in out.values() if v.k == k) for k in KINDS}
    cyclic = tuple(sg for sg, v in out.items() if v.kind == 'cyclic')
    if counts != SURVEY_COUNTS or cyclic != SURVEY_CYCLIC:
        raise RuntimeError(f'orthorhombic axis-order classes {counts} (cyclic {cyclic}) differ from the survey of '
                           f'2026-10-21 {SURVEY_COUNTS} (cyclic {SURVEY_CYCLIC}): the tables changed')
    return out


def axis_orders(sg: int) -> AxisOrders:
    """The allowed axis orders of orthorhombic space group ``sg`` (16-74), derived at first use (module docstring)."""
    sg = int(sg)
    if sg not in ORTHORHOMBIC:
        raise ValueError(f'axis orders are defined for the orthorhombic groups 16-74, not {sg}')
    if not _ORDERS:
        _ORDERS.update(_derive_all())
    return _ORDERS[sg]


def classes() -> Dict[int, Tuple[int, ...]]:
    """{number of allowed orders: the orthorhombic groups with that many}."""
    out = {k: [] for k in KINDS}
    for sg in ORTHORHOMBIC:
        out[axis_orders(sg).k].append(sg)
    return {k: tuple(v) for k, v in out.items()}


class OrthoCellChart:
    """y = (log a, log b, log c) of orthorhombic cells (alpha = beta = gamma = pi/2), with the faces of one group.

    ``unmap(cell) -> (y, None)``, ``map(y) -> (cell, None)`` (angles exactly pi/2), as ``charts.CellChart`` returns
    them; ``faces`` [m, 3] with face values ``y @ faces.T`` (``AxisOrders.faces``); ``family`` 'orthorhombic'.
    """
    family = 'orthorhombic'

    def __init__(self, sg: int):
        self.sg = int(sg)
        self.orders = axis_orders(sg)
        self.faces = self.orders.faces

    def unmap(self, cell: torch.Tensor):
        return torch.log(torch.as_tensor(cell, dtype=F64)[:, :3]), None

    def map(self, y: torch.Tensor):
        y = torch.as_tensor(y, dtype=F64)
        return torch.cat([torch.exp(y), torch.full_like(y, torch.pi / 2)], 1), None


def cell_chart(sg: int) -> OrthoCellChart:
    """The ``OrthoCellChart`` of group ``sg`` (16-74), cached."""
    sg = int(sg)
    if sg not in _CHARTS:
        _CHARTS[sg] = OrthoCellChart(sg)
    return _CHARTS[sg]


def _face_dot(y: torch.Tensor, A: torch.Tensor) -> torch.Tensor:
    """[..., m] face values y . A_r of log lengths y [..., 3], as explicit elementwise products and sums in a fixed
    order, so that a row's values do not depend on the shape of the batch it is computed in."""
    A = A.to(y.device)
    return y[..., 0, None] * A[:, 0] + y[..., 1, None] * A[:, 1] + y[..., 2, None] * A[:, 2]


def face_values(sg: int, cell: torch.Tensor) -> torch.Tensor:
    """[b, m] face values (log-length differences) of cells of group ``sg`` in the group's chart; m = 0 for k = 1."""
    chart = cell_chart(sg)
    y, _ = chart.unmap(cell.detach().to('cpu', F64))
    return _face_dot(y, chart.faces).to(cell.device)


def choose(sg: int, cell: torch.Tensor, tol: float, face_tol: float):
    """The canonical axis order of orthorhombic cells of one group (module docstring).

    Parameters
    ----------
    cell : [b, 6]
        Cells at the group's exact metric (angles pi/2; only the lengths are read).
    tol : float
        Tie tolerance on log lengths (``canon``'s ``cell_tol``).
    face_tol : float
        Tolerance on log lengths within which an allowed order is counted as an automorphism (``n_auto``).

    Returns
    -------
    (pick [b] long index into ``AxisOrders.perm``, n_tied [b] long (orders whose cell lies in the closed domain
    within ``tol``; 1 off faces), n_auto [b] long (the order of the subgroup generated by the orders giving the chosen
    cell within ``face_tol``, module docstring; 1 generic), violation [b] (largest face violation of the chosen cell,
    <= ``tol``), face [b] (smallest face value of the chosen cell, log units; NaN where the group has no faces))
    """
    from mxtaltools.crystal_fd.ops import _lex_select
    orders = axis_orders(sg)
    dev = cell.device
    logL = torch.log(torch.as_tensor(cell, dtype=F64)[:, :3])                       # [b, 3]
    perm = orders.perm.to(dev)
    keys = logL[:, perm]                                                            # [b, k, 3]
    b, k = keys.shape[:2]
    if k == 1:
        one = torch.ones(b, dtype=torch.long, device=dev)
        return (torch.zeros(b, dtype=torch.long, device=dev), one, one.clone(), torch.zeros(b, dtype=F64, device=dev),
                torch.full((b,), float('nan'), dtype=F64, device=dev))
    pick = _lex_select(keys, torch.ones(b, k, dtype=torch.bool, device=dev), tol, largest=False)
    fv = _face_dot(keys, orders.faces)                                              # [b, k, m]
    viol = (-fv).clamp(min=0).amax(-1)                                              # [b, k]
    rows = torch.arange(b, device=dev)
    chosen = keys[rows, pick]                                                       # [b, 3]
    # the orders of the chosen cell that give it back within face_tol (identity included), then their subgroup
    within = (chosen[:, perm] - chosen[:, None]).abs().amax(-1) <= face_tol         # [b, k]
    n_auto = _generated(within, orders.comp.to(dev)).sum(1)
    return pick, (viol <= tol).sum(1), n_auto, viol[rows, pick], fv[rows, pick].amin(-1)


def _generated(mask: torch.Tensor, comp: torch.Tensor) -> torch.Tensor:
    """[b, k] bool: the subgroup generated by the orders in ``mask`` (each row holds the identity) under ``comp``.

    Each round adds every product of two members. A round that adds nothing ends the loop; every other round adds at
    least one of the k orders to a set that starts with one, so the loop ends within k rounds, at the closure."""
    k = comp.shape[0]
    hit = torch.nn.functional.one_hot(comp, k).bool()                              # [k, k, k]: comp[i, j] == l
    for _ in range(k):
        new = mask | (mask[:, :, None, None] & mask[:, None, :, None] & hit[None]).any(2).any(1)
        if torch.equal(new, mask):
            break
        mask = new
    return mask
