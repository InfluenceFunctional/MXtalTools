"""Write configs/<model>_known.yaml and configs/<model>_search.yaml for every model of models.py (cluster paths).

    <model>_known   the known forms ACRDIN04 and ACRDIN12 as the only seeds, no random start, no stop rule: each form's
                    minimum under the model, the reference a search's recall is read against
    <model>_search  the seed pool (21,882 states of the earlier acridine landscapes) first, then up to N_RANDOM random
                    starts; the seeds and the starts each end by the Good-Turing stop rule (STOP_P, STOP_BAND_KT)

run.py builds the seed files these name (seeds_<model>_{known,pool}.pt in models.OUT) before it runs them.

usage: python make_configs.py
"""
import os

import yaml

import models as M


def main():
    out = os.path.join(M.HERE, 'configs')
    os.makedirs(out, exist_ok=True)
    for model in M.MODELS:
        for kind in ('known', 'search'):
            run = f'{model}_{kind}'
            seeds = f'{M.OUT}/seeds_{model}_{"known" if kind == "known" else "pool"}.pt'
            c = M.config(model, run, seeds, num_samples=0 if kind == 'known' else M.N_RANDOM,
                         stop_p=None if kind == 'known' else M.STOP_P)
            path = os.path.join(out, f'{run}.yaml')
            with open(path, 'w') as fh:
                fh.write(f'# acr_mlip_nov17: acridine P2_1/c Z\'=1, {model}, {kind}. Generated by make_configs.py; '
                         f'edit models.py and regenerate.\n')
                yaml.safe_dump(c, fh, sort_keys=False)
            print(path)


if __name__ == '__main__':
    main()
